#!/usr/bin/env node
/* Wraps data/database.json as a classic script (js/db.js) so index.html works by double-click (file://),
   where fetch() and ES modules are blocked. Also validates the database and writes CSV exports.
   Usage: node tools/build-db.js */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const db = JSON.parse(fs.readFileSync(path.join(root, 'data', 'database.json'), 'utf8'));

const errors = require('../tests/validate').validate(db);
if (errors.length) {
  console.error('Database validation failed:\n - ' + errors.join('\n - '));
  process.exit(1);
}

const banner = '/* GENERATED by tools/build-db.js from data/database.json. Do not edit by hand. */\n';
fs.writeFileSync(path.join(root, 'js', 'db.js'), banner + 'window.DigitasDB = ' + JSON.stringify(db, null, 2) + ';\n');

// CSV exports: the brief says a spreadsheet is fine, so each table is also available as CSV.
const csvDir = path.join(root, 'data', 'csv');
fs.mkdirSync(csvDir, { recursive: true });
const esc = (v) => {
  const s = Array.isArray(v) ? v.join('; ') : (v == null ? '' : String(v));
  return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
};
const toCsv = (rows, cols) => [cols.join(',')].concat(rows.map(r => cols.map(c => esc(r[c])).join(','))).join('\n') + '\n';
const write = (name, rows, cols) => fs.writeFileSync(path.join(csvDir, name + '.csv'), toCsv(rows, cols));

write('specialties', db.specialties, ['order', 'id', 'name', 'description', 'subCapabilities', 'team', 'role', 'source']);
write('case_studies', db.caseStudies, ['id', 'client', 'year', 'problemLabel', 'demoSlot', 'specialtiesUsed', 'linesConnected', 'result', 'sourceLink', 'verified', 'note']);
write('problem_map', db.problemMap.flatMap(p => p.lines.length
  ? p.lines.map(l => ({ problem: p.id, points: p.points, line: l.line, sentence: l.sentence, status: p.status }))
  : [{ problem: p.id, points: p.points, line: '', sentence: '', status: p.status }]),
  ['problem', 'points', 'line', 'sentence', 'status']);
write('cost_assumptions', db.costAssumptions.rows.map(r => ({
  row: r.label, type: r.type, formula: r.formula,
  specialistOnly: JSON.stringify(r.specialist), digitasConnected: JSON.stringify(r.digitas), source: r.source })),
  ['row', 'type', 'formula', 'specialistOnly', 'digitasConnected', 'source']);
write('collaboration_rules', [{
  ownershipDefault: db.collaborationRules.ownershipDefault,
  owningAgencyResponsibilities: db.collaborationRules.responsibilitiesTemplate.owningAgency,
  digitasResponsibilities: db.collaborationRules.responsibilitiesTemplate.digitas,
  creditSplit: db.collaborationRules.creditSplit.label,
  integrationLeadRole: db.collaborationRules.integrationLeadRole }],
  ['ownershipDefault', 'owningAgencyResponsibilities', 'digitasResponsibilities', 'creditSplit', 'integrationLeadRole']);

console.log('Built js/db.js and data/csv/*.csv (' + db.specialties.length + ' specialties, ' + db.lines.length + ' lines, ' +
  db.caseStudies.length + ' case studies).');
